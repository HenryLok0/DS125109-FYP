let current = "zh";

export function getLang() {
  return current;
}

export function setLang(lang) {
  current = lang === "en" ? "en" : "zh";
  document.documentElement.lang = current === "zh" ? "zh-Hant" : "en";
  localStorage.setItem("easepark.lang", current);
}

export function initLang() {
  const saved = localStorage.getItem("easepark.lang");
  if (saved) setLang(saved);
  else setLang(navigator.language?.toLowerCase().startsWith("en") ? "en" : "zh");
}

export function t(key, vars) {
  const table = DICT[current] || DICT.zh;
  let text = table[key] ?? DICT.zh[key] ?? key;
  if (vars) text = text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
  return text;
}
